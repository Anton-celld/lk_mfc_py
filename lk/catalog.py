KEY_RE = re.compile(r"^[A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё0-9_]{0,40}$")


def clean_tpl(t):
    """Шаблон заявления из конструктора: только известные поля, ограничения длины."""
    if not isinstance(t, dict):
        raise ValueError("неверный шаблон")
    out = {k: str(t.get(k) or "")[:4000] for k in ("to", "head", "body")}
    out["file"] = str(t.get("file") or "")[:200]
    out["draft"] = 1 if t.get("draft") else 0
    if not out["body"].strip():
        raise ValueError("текст заявления не может быть пустым")
    fields, seen = [], set()
    for f in (t.get("fields") or [])[:30]:
        k = str(f.get("k") or "")
        if not KEY_RE.match(k) or k in seen:
            raise ValueError(f"неверный ключ поля: {k!r}")
        seen.add(k)
        typ = f.get("type") if f.get("type") in apps.TYPES else "text"
        x = {"k": k, "l": str(f.get("l") or k)[:120], "type": typ, "req": 1 if f.get("req") else 0, "ph": str(f.get("ph") or "")[:160]}
        # правила дат и расчёта из шаблона сохраняются как есть (в конструкторе их не меняют)
        for extra in ("calc", "min", "helper", "acc", "note", "src", "dep", "other", "dirk", "course", "nmin", "unit", "show"):
            if f.get(extra):
                x[extra] = f[extra]
        if typ == "calc" and not isinstance(x.get("calc"), dict):
            x["type"] = "date"
        if typ == "select":
            x["opts"] = [str(o)[:160] for o in (f.get("opts") or []) if str(o).strip()][:40] or ["—"]
        fields.append(x)
    out["fields"] = fields
    return out


