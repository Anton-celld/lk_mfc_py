def is_final(o):
    """Конечный статус: после него заказ через keep_days дней уходит в архив и можно оставить отзыв.

    Для обычных заявлений передача в дирекцию — конечный этап. В зависимости от того,
    какой статус прислала 1С, это может быть «work» или «sign». Заявление на справку
    о периоде обучения имеет flow=long и продолжает идти по полному маршруту.
    """
    flow = flow_of(o)
    return (o["status"] in ("done", "rej", "cancel", "signed") or
            (flow == "app" and o["status"] in ("work", "sign")))


def can_review(o):
    flow = flow_of(o)
    return (o["status"] in ("done", "signed") or
            (flow == "app" and o["status"] in ("work", "sign")))


