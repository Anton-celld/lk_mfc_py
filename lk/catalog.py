def _norm_kind(t):
    return re.sub(r"[^а-я0-9 ]", "", re.sub(r"\s+", " ", str(t or "").lower().replace("ё", "е"))).strip()


def extract_allowed(prikaz, foreign):
    """Можно ли заказать выписку из этого приказа. Иностранцам — только виды из FOREIGN_EXTRACTS
    (вид приказа 1С присылает в поле type; если нет — сравниваем по началу заголовка)."""
    if not foreign:
        return True
    t = _norm_kind(prikaz.get("type") or prikaz.get("title"))
    return any(t == _norm_kind(k) or t.startswith(_norm_kind(k)) for k in FOREIGN_EXTRACTS)


def is_foreign(person):
    """Иностранный гражданин (без гражданства РФ). 1С присылает citizenship; foreign — запасной признак."""
    if "foreign" in person:
        return bool(person["foreign"])
    c = str(person.get("citizenship") or "").strip().lower()
    return bool(c) and c not in ("россия", "рф", "российская федерация", "643")


