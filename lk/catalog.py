def dir_label(d):
    return f"{d['code']} {d['name']}"


def src_opts(f, vals, level, s=None):
    """Варианты выпадашки, которые зависят от данных: институты → направления института → профили направления."""
    L = directions(level, s)
    src, dep = f.get("src"), vals.get(f.get("dep") or "", "")
    if src == "inst":
        return sorted({d["inst"] for d in L})
    if src == "dir":
        return [dir_label(d) for d in L if not f.get("dep") or d["inst"] == dep]
    if src == "prof":
        d = next((d for d in L if dir_label(d) == dep), None)
        return [x["name"] for x in d["profiles"]] if d else []
    if src == "form":
        # КЦП — набор этого года, т. е. нынешний 1-й курс: на 1-й курс — только формы, где по КЦП есть места;
        # на 2-й и старше группы набраны в прошлые годы — показываем все формы, есть ли группа, решает МФЦ
        if str(vals.get(f.get("course") or "", "") or "1") != "1":
            return [g for _, g in FORMS_G]
        d = next((d for d in L if dir_label(d) == vals.get(f.get("dirk") or "", "")), None)
        pr = next((x for x in (d or {}).get("profiles", []) if x["name"] == dep), None)
        return [g for n, g in FORMS_G if n in (pr or {}).get("forms", [])]
    return list(f.get("opts") or [])


