# Винительный падеж для «Что прилагаете»: «справка» → «справку», «медицинская справка» → «медицинскую справку».
# Меняются только прилагательные в начале и первое существительное на -а/-я — дальше обычно род. падеж («копия паспорта»).
_ADJ = (("ая", "ую"), ("яя", "юю"))
_NOUN = (("ия", "ию"), ("ья", "ью"), ("а", "у"), ("я", "ю"))
_KEEP = {"сам", "одна", "пара"}


def accusative(text):
    words, out, done = str(text or "").split(" "), [], False
    for w in words:
        lw = w.lower()
        if not done and lw.isalpha() and lw not in _KEEP:
            for a, b in _ADJ:
                if lw.endswith(a) and len(lw) > 3:
                    w = w[:-2] + (b.upper() if w[-2:].isupper() else b)
                    break
            else:
                for a, b in _NOUN:
                    if lw.endswith(a) and len(lw) > 2:
                        w = w[:-len(a)] + b
                        break
                done = True
        elif not done:
            done = True
        out.append(w)
    return " ".join(out)
