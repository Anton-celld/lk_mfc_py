"""Сквозная проверка в браузере на запущенном демо (python run.py --demo). Запуск: python tests/e2e.py http://127.0.0.1:8090 папка_скриншотов"""
import sys

from playwright.sync_api import sync_playwright

URL, SHOTS = sys.argv[1].rstrip("/"), sys.argv[2]
errs, log = [], []


def ok(c, m):
    log.append(("OK  " if c else "FAIL") + " " + m)


with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 1280, "height": 900}, locale="ru-RU")
    pg = ctx.new_page()
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("console", lambda m: errs.append("console: " + m.text) if m.type == "error" and "401" not in m.text else None)
    pg.add_init_script("window.print=()=>{window.__printed=(window.__printed||0)+1}")

    def login(who):
        pg.goto(URL + "/")
        pg.wait_for_selector("#vLogin:not([hidden])")
        pg.fill("#lLogin", who)
        pg.fill("#lPass", "demo2026")
        pg.click("#loginForm button[type=submit]")

    def has_toast(s):
        try:
            pg.wait_for_function("s=>{const t=document.querySelector('#toast');return !t.hidden&&t.textContent.includes(s)}", arg=s, timeout=6000)
            return True
        except Exception:  # noqa
            return False

    def svc(t):
        pg.click(".tabs [data-tab=new]")
        pg.locator(".svc", has_text=t).first.click()

    def form():
        return pg.inner_text(".form")

    # ---- вход
    pg.goto(URL + "/")
    pg.wait_for_selector("#vLogin:not([hidden])")
    pg.wait_for_timeout(300)
    ok("Демо-режим" in pg.inner_text("#lDemo"), "экран входа, подсказка демо")
    pg.screenshot(path=f"{SHOTS}/e01_login.png")
    pg.fill("#lLogin", "st100001")
    pg.fill("#lPass", "неверный")
    pg.click("#loginForm button[type=submit]")
    pg.wait_for_selector("#lErr:not([hidden])")
    ok("Неверный логин или пароль" in pg.inner_text("#lErr"), "неверный пароль — понятная ошибка")
    login("st100001")
    pg.wait_for_selector("#vApp:not([hidden])")
    ok("Иванов Иван Иванович" in pg.inner_text("#meName"), "вошли как студент, ФИО из 1С")
    ok("mfts@rgau-msha.ru" in pg.inner_text(".foot") and "+7 (499) 977-14-33" in pg.inner_text(".foot"), "внизу контакты МФЦ")
