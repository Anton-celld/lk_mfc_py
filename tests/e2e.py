    # ---- ЭЦП: печатная форма, подтверждение, подпись Захаровой
    svc("Справка о подтверждении обучения")
    pg.click("[data-kind=ecp]")
    ok("Перед отправкой вы увидите справку и подтвердите" not in form(), "блок про подписанта в форме убран")
