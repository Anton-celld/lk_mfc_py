    ok(max(vals) == cur, f"последний месяц в списке — прошлый (или текущий в последние 4 дня): {cur}")
    svc("Выписка из приказа")
    pg.wait_for_selector("#f_ord")
    ok(pg.locator("#f_ord option").count() - 1 == 4, "выписка: все 4 приказа студента из 1С")
    # ---- справка «по месту требования» и с ЭЦП — без организации
    svc("Справка о подтверждении обучения")
    ok(pg.inner_text("[data-kind=umu]").startswith("Справка о подтверждении обучения по месту требования") and "Студенческом МФЦ" in pg.inner_text("[data-kind=umu]"), "виды справки: где какая выдаётся")
    ok("Получение — в личном кабинете" in pg.inner_text("[data-kind=ecp]") and "Социального фонда" in pg.inner_text("[data-kind=gerb]"), "виды справки: тексты МФЦ")
    ok("Сюда придут" not in form() and "Перед отправкой вы увидите справку и подтвердите" not in form(), "лишние подсказки убраны")
    ok("Иванов Иван Иванович" in pg.inner_text(".who-box") and "ЭК-301" in pg.inner_text(".who-box"), "данные заказчика подставлены")
    pg.click("[data-kind=umu]")
    ok(pg.locator("#f_orgq").count() == 0, "по месту требования — без организации по ИНН")
    pg.click("[data-kind=ecp]")
    ok(pg.locator("#f_orgq").count() == 0, "с ЭЦП — без организации по ИНН")
    # ---- справка-вызов: основание списком, даты из графика, без экземпляров и ФИО руководителя
