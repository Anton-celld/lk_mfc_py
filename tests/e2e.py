    pg.select_option("#f_НоваяСпециальность", "35.03.04 Агрономия")
    pg.wait_for_timeout(100)
    pr = pg.eval_on_selector_all("#f_НоваяСпециализация option", "o=>o.map(x=>x.value).filter(Boolean)")
