    pg.click(".tabs [data-tab=new]")
    n = pg.locator(".svc").count()
    ok(n == 24, f"каталог бакалавра: 5 справок и выписок + 19 заявлений ({n})")
    ok(pg.locator(".svc span").count() == 0, "в карточках каталога только названия, без описаний")
    ok(pg.inner_text("#meLevel") == "Бакалавриат, 3 курс", "в шапке — свой уровень программы, а не «Бакалавриат, специалитет»")
    ok("учитесь по" not in pg.inner_text("main"), "нет надписи «Вы учитесь по N программам»")
    pg.screenshot(path=f"{SHOTS}/e02_catalog.png", full_page=True)

    # ---- справка об обучении: гербовая, ИНН, лимит
