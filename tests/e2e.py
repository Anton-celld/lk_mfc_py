    pg.select_option("#f_reason", "Прохождение промежуточной аттестации")
    ok(pg.locator("#f_from").count() == 0 and pg.locator("#f_call option").count() == 3, "по графику две сессии — выбор периода")
    pg.select_option("#f_call", "p1-w")
    ok("с 11.01.2027 по 31.01.2027" in form(), "вызов: даты подставились по основанию")
    pg.screenshot(path=f"{SHOTS}/e03b_call.png", full_page=True)
    pg.fill("#f_orgq", "7700000016")
    pg.wait_for_selector("#orgL [data-org]:not([disabled])")
    pg.click("#orgL [data-org]")
    pg.click("[data-a=preview]")
    pg.wait_for_selector("#printArea")
    cp = pg.inner_text("#printArea").replace("\xa0", " ")
    ok("СПРАВКА-ВЫЗОВ" in cp and "прохождения промежуточной аттестации" in cp and "173" in cp and "Иванову Ивану Ивановичу" in cp, "справка-вызов: предпросмотр по форме № 1368")
    pg.screenshot(path=f"{SHOTS}/e03c_call_preview.png", full_page=True)
    pg.check("#okChk")
    pg.click("#okGo")
    ok(has_toast("отправлена в МФЦ"), "справка-вызов отправлена после проверки")
    svc("Справка-вызов")
    pg.select_option("#f_reason", "Прохождение промежуточной аттестации")
    ok(pg.locator("#f_call option[value='p1-w']").count() == 1, "уже заказанный период можно заказать снова")
    # ---- вторая зачётка: свои заказы, свой уровень
    pg.click(".tabs [data-tab=orders]")
    n1 = pg.locator(".ord").count()
    pg.select_option("#prog", "p2")
    pg.wait_for_timeout(600)
    ok(pg.inner_text("#meLevel") == "Специалитет, 3 курс", "вторая программа — специалитет")
    ok(pg.locator(".ord", has_text="Справка-вызов").count() == 0 and pg.locator(".ord").count() != n1, "заказы первой зачётки во второй не видны")
    pg.screenshot(path=f"{SHOTS}/e03d_prog2.png", full_page=True)
    pg.select_option("#prog", "p1")
    pg.wait_for_timeout(600)

    # ---- пачка 3: «иные обстоятельства» вписываются вручную; перевод — выпадашки по КЦП
    svc("Заявление на досрочную сдачу сессии")
    ok("Скачайте бланк" not in form() and "Загрузите бланк" in form() and "Приложите сканированные копии" in form(), "шаги: «Загрузите бланк», «Приложите сканированные копии»")
    ok("Приложенные документы (указать в винительном падеже)" in form() and "прилагаю что" not in form(), "«Приложенные документы» без подсказки")
    ok(pg.locator("#f_Причина_иное").count() == 0, "поля «иные» нет, пока не выбраны иные обстоятельства")
    pg.select_option("#f_Причина", "иными обстоятельствами")
    pg.wait_for_selector("#f_Причина_иное")
    pg.click("[data-a=nextstep]")
    ok("Укажите, какие именно обстоятельства" in form(), "иные обстоятельства — нужно вписать")
    pg.fill("#f_Причина_иное", "участием в международной олимпиаде")
    pg.click("[data-a=nextstep]")
    pg.click("[data-a=blank]")
    pg.wait_for_selector("#printArea")
    ok("в связи с иными обстоятельствами (участием в международной олимпиаде)" in pg.inner_text("#printArea").replace("\xa0", " "), "в бланке — иные обстоятельства в скобках")
    pg.click("#sheetBody [data-x]")
    pg.click("[data-a=s1]")
    svc("Заявление на перевод на другое направление")
    ok(pg.locator("#f_НовыйФакультет option").count() == 8, "институты — выпадашкой (7)")
    ok(pg.is_disabled("#f_НоваяСпециальность") and pg.is_disabled("#f_НоваяСпециализация"), "направление и профиль ждут выбора института")
