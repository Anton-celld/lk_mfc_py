    pg.wait_for_selector("#printArea")
    paper = pg.inner_text("#printArea").replace("\xa0", " ")
    ok("о подтверждении обучения" in paper and "Иванов Иван Иванович (дата рождения 14.03.2004 г.)" in paper and "С.А. Захарова" in paper, "печатная форма по образцу 1С до подтверждения")
    ok("mfts@rgau-msha.ru" in pg.inner_text("#sheetBody") and "977-14-33" in pg.inner_text("#sheetBody"), "в предпросмотре — контакты МФЦ на случай ошибки")
    pg.screenshot(path=f"{SHOTS}/e04_ecp_preview.png", full_page=True)
    ok(pg.is_disabled("#okGo"), "без галочки подтвердить нельзя")
    pg.check("#okChk")
    pg.click("#okGo")
    ok(has_toast("отправлена на подпись"), "подтвердили — ушла на подпись")
    ok("Передано на подпись" in pg.locator(".ord", has_text="с ЭЦП").first.inner_text(), "статус «Передано на подпись»")

