    pg.fill("#askQ", "Когда будет готова справка?")
    pg.click("#askGo")
    ok(pg.get_attribute("#askGo", "href").startswith("mailto:mfts@rgau-msha.ru?subject="), "«Есть вопрос» — письмо в МФЦ с данными студента")
