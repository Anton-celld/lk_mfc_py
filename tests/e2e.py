    pg.click("#sheetBody [data-x]")
    ok(pg.locator("#prog option").count() == 2, "две программы обучения в переключателе")
    ok(pg.evaluate("getComputedStyle(document.body).fontFamily").startswith("Montserrat"), "шрифт Montserrat")
    ok(pg.evaluate("getComputedStyle(document.body).backgroundColor") == "rgb(255, 255, 255)", "белый фон")
    pg.emulate_media(color_scheme="dark")
    ok(pg.evaluate("getComputedStyle(document.body).backgroundColor") == "rgb(255, 255, 255)", "белый и при тёмной теме системы")
