    pg.click("[data-kind=gerb]")
    pg.click("[data-a=submit]")
    ok("Выберите организацию по ИНН" in form(), "гербовая без организации — ошибка")
    pg.fill("#f_orgq", "7700000011")
    ok("контрольная цифра" in pg.inner_text("#orgL"), "ИНН с ошибкой в контрольной цифре")
    pg.fill("#f_orgq", "7700000062")
    pg.wait_for_selector("#orgL [data-org]")
    ok(pg.locator("#orgL [data-org][disabled]").count() == 1, "ликвидированную организацию выбрать нельзя")
    pg.fill("#f_orgq", "7700000016")
    pg.wait_for_selector("#orgL [data-org]:not([disabled])")
    pg.click("#orgL [data-org]")
    ok("Агрохолдинг" in pg.inner_text(".org-pick"), "организация подставилась из ЕГРЮЛ")
    ok(pg.get_attribute("#f_qty", "max") == "3", "экземпляры: поле с ограничением до 3")
    pg.fill("#f_qty", "5")
    ok(pg.input_value("#f_qty") == "3" and has_toast("Не больше 3"), "5 экземпляров ввести нельзя — стало 3")
